// Generates a repository CI gate for budget.json: a dependency-free Node script plus a GitHub
// Actions workflow that runs on every pull request, measures the real build (payload sizes and,
// when limited, Lighthouse LCP/CLS) and fails the check with the named fix. Same metrics, limits
// and fix advice as the agent's preflight (perf-budget.ts), so CI and Forge never disagree.
import { HINT, LABEL, METRICS } from "./perf-budget";

export const BUDGET_SCRIPT_PATH = ".github/scripts/forge-budget-check.mjs";
export const BUDGET_WORKFLOW_PATH = ".github/workflows/forge-budget.yml";

export function budgetCheckScript(): string {
  return `#!/usr/bin/env node
// Generated by Forge. Enforces budget.json on the built app. Exit 1 = budget breached or a limited metric could not be measured.
import { readFileSync, readdirSync, statSync, existsSync, appendFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { spawn, execFileSync } from "node:child_process";

const METRICS = ${JSON.stringify(METRICS)};
const HINT = ${JSON.stringify(HINT, null, 2)};
const LABEL = ${JSON.stringify(LABEL, null, 2)};
const arg = (n) => { const i = process.argv.indexOf("--" + n); return i > 0 ? process.argv[i + 1] : undefined; };
const root = resolve(arg("root") ?? ".");
const fail = (msg) => { console.log("::error title=Performance budget::" + msg); summary("### Performance budget\\n\\n" + msg + "\\n"); process.exit(1); };
function summary(md) { if (process.env.GITHUB_STEP_SUMMARY) appendFileSync(process.env.GITHUB_STEP_SUMMARY, md + "\\n"); }

const budgetFile = join(root, "budget.json");
if (!existsSync(budgetFile)) { console.log("No budget.json — nothing to enforce."); process.exit(0); }
let budget;
try { budget = JSON.parse(readFileSync(budgetFile, "utf8")); } catch { fail("budget.json must contain valid JSON."); }
if (!budget || typeof budget !== "object" || Array.isArray(budget)) fail("budget.json must be an object of limits.");
const unknown = Object.keys(budget).filter((k) => !METRICS.includes(k));
if (unknown.length) fail("budget.json has unknown limits: " + unknown.join(", ") + ". Allowed: " + METRICS.join(", ") + ".");
for (const [k, v] of Object.entries(budget)) if (typeof v !== "number" || !Number.isFinite(v) || v < 0) fail("budget.json " + k + " must be a non-negative number.");
if (!Object.keys(budget).length) fail("budget.json declares no limits.");

const distArg = arg("dist");
const dist = distArg ? resolve(root, distArg) : ["dist/client", "dist", "build", "out", ".output/public", ".vercel/output/static", ".next/static"].map((d) => join(root, d)).find((d) => existsSync(d) && statSync(d).isDirectory());
const measured = {};
if (dist) {
  const files = [];
  const walk = (d) => { for (const n of readdirSync(d)) { if (n === "node_modules") continue; const p = join(d, n); const s = statSync(p); if (s.isDirectory()) walk(p); else files.push({ p, b: s.size }); } };
  walk(dist);
  const sum = (exts) => files.filter((f) => !f.p.endsWith(".map") && exts.some((e) => f.p.endsWith(e))).reduce((n, f) => n + f.b, 0) / 1024;
  const js = sum([".js", ".mjs"]), css = sum([".css"]);
  measured.jsKb = Math.round(js * 10) / 10; measured.cssKb = Math.round(css * 10) / 10; measured.totalKb = Math.round((js + css) * 10) / 10;
}

async function lighthouse() {
  let url = arg("url"); let server;
  if (!url) {
    const site = dist && [dist, join(dist, "..")].find((d) => existsSync(join(d, "index.html")));
    if (!site) return "no index.html in the build output to load (pass --url to a running preview)";
    server = spawn("npx", ["--yes", "serve@14", "-s", site, "-l", "4173"], { stdio: "ignore" });
    url = "http://localhost:4173";
    for (let i = 0; i < 40; i++) { try { await fetch(url); break; } catch { await new Promise((r) => setTimeout(r, 500)); } }
  }
  try {
    const runs = [];
    for (let i = 0; i < 3; i++) {
      execFileSync("npx", ["--yes", "lighthouse@12", url, "--quiet", "--only-categories=performance", "--output=json", "--output-path=/tmp/forge-lh.json", "--chrome-flags=--headless=new --no-sandbox"], { stdio: "ignore", timeout: 180000 });
      const a = JSON.parse(readFileSync("/tmp/forge-lh.json", "utf8")).audits;
      runs.push({ lcp: a["largest-contentful-paint"]?.numericValue, cls: a["cumulative-layout-shift"]?.numericValue });
    }
    const median = (xs) => { const v = xs.filter((x) => typeof x === "number").sort((a, b) => a - b); return v.length ? v[Math.floor(v.length / 2)] : undefined; };
    const lcp = median(runs.map((r) => r.lcp)), cls = median(runs.map((r) => r.cls));
    if (lcp !== undefined) measured.lcpMs = Math.round(lcp);
    if (cls !== undefined) measured.cls = Math.round(cls * 1000) / 1000;
  } catch (e) { return "Lighthouse failed: " + (e?.message ?? e); }
  finally { server?.kill(); }
}
let lhNote;
if (budget.lcpMs !== undefined || budget.cls !== undefined) lhNote = await lighthouse();

const rows = [], violations = [], unmeasured = [];
for (const m of METRICS) {
  if (budget[m] === undefined) continue;
  const actual = measured[m];
  if (typeof actual !== "number") { unmeasured.push(m); rows.push("| " + LABEL[m] + " | " + budget[m] + " | not measured | ⚠️ unverified |"); continue; }
  const over = actual > budget[m];
  if (over) violations.push(m);
  rows.push("| " + LABEL[m] + " | " + budget[m] + " | " + actual + " | " + (over ? "❌ over" : "✅ ok") + " |");
}
let md = "### Performance budget\\n\\n| Metric | Limit | Actual | Result |\\n|---|---|---|---|\\n" + rows.join("\\n") + "\\n";
for (const m of violations) { console.log("::error title=" + LABEL[m] + " over budget (" + measured[m] + " > " + budget[m] + ")::Fix: " + HINT[m]); md += "\\n**" + LABEL[m] + "** — fix: " + HINT[m] + "\\n"; }
for (const m of unmeasured) console.log("::error title=" + LABEL[m] + " not measured::" + (m === "lcpMs" || m === "cls" ? (lhNote ?? "no Lighthouse result") : "no build output found (run the build first or pass --dist)") + ". Unmeasured limits never pass.");
if (unmeasured.length) md += "\\nNot measured (never counts as passing): " + unmeasured.map((m) => LABEL[m]).join(", ") + (lhNote ? " — " + lhNote : "") + "\\n";
summary(md); console.log(md);
process.exit(violations.length || unmeasured.length ? 1 : 0);
`;
}

/** Workflow for one project root (monorepo-aware). Runs on pull requests and Forge task branches. */
export function budgetWorkflow(root = "."): string {
  const dir = root.replace(/^\.\/?/, "") || ".";
  return `# Generated by Forge: fails the PR check when the build breaks budget.json, naming the fix.
name: Performance budget
on:
  pull_request:
  push:
    branches: ["forge/**", "agent/**"]
permissions:
  contents: read
concurrency:
  group: budget-\${{ github.ref }}
  cancel-in-progress: true
jobs:
  budget:
    runs-on: ubuntu-latest
    timeout-minutes: 25
    defaults:
      run:
        working-directory: ${JSON.stringify(dir)}
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: 20
      - uses: oven-sh/setup-bun@v2
        if: hashFiles('**/bun.lockb', '**/bun.lock') != ''
      - name: Install
        run: |
          if [ -f bun.lockb ] || [ -f bun.lock ]; then bun install --frozen-lockfile || bun install
          elif [ -f pnpm-lock.yaml ]; then npx --yes pnpm@9 install --frozen-lockfile
          elif [ -f yarn.lock ]; then npx --yes yarn@1 install --frozen-lockfile
          else npm ci || npm install; fi
      - name: Build
        run: npm run build
      - name: Enforce budget.json
        run: node ${dir === "." ? "" : "$GITHUB_WORKSPACE/"}${BUDGET_SCRIPT_PATH} --root .
`;
}
